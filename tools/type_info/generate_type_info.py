@dataclass
class Frame:
	kind: str  # file, namespace, class, block
	qualname: str = ""
	name: str | None = None
	stmt: list = field(default_factory=list)
	skip_stmt: bool = False
	marker: tuple | None = None  # (saved_name, token) of a pending BLK_PROPERTY
	component: Component | None = None
	props: list = field(default_factory=list)
	closes_stmt: bool = False  # a function body: closing it ends the enclosing statement


def scoped(outer, name):
	return f"{outer}::{name}" if outer else name


def unquote(token):
	return token.text[1:-1]


# Specifier -> (value kind, wired up yet). Anything else in a marker is a build error,
# and so is a specifier that parses but nothing acts on, so a hint can't silently do
# nothing. Flip the flag in the same change that makes one take effect.
PROPERTY_SPECIFIERS = {
	"SerializedAs": ("string", True),
	"MinVal": ("number", True),
	"MaxVal": ("number", True),
}
ENUM_SPECIFIERS = {
	"SerializedAs": ("string", True),
	"Skip": ("flag", True),
}


def parse_specifiers(tokens, table, marker, report):
	"""Reads a marker's Key = value list. Returns {name: value}; flags map to True."""
	specs = {}
	i = 0
	while i < len(tokens):
		name = tokens[i]
		if name.kind != "ident" or name.text not in table:
			report(marker.line, f"{marker.text}: unknown specifier '{name.text}'; expected one of {', '.join(table)}")
			return specs
		kind, implemented = table[name.text]
		if not implemented:
			report(marker.line, f"{marker.text}: {name.text} isn't wired up yet, so it would have no effect")
			return specs
		i += 1
		value = True
		if i < len(tokens) and tokens[i].text == "=":
			i += 1
			if kind == "flag":
				report(marker.line, f"{marker.text}: {name.text} takes no value")
				return specs
			negate = i < len(tokens) and tokens[i].text == "-"
			i += negate
			token = tokens[i] if i < len(tokens) else None
			if kind == "string" and (token is None or token.kind != "string"):
				report(marker.line, f'{marker.text}: {name.text} takes a string, as {name.text} = "Something"')
				return specs
			if kind == "number" and (token is None or token.kind != "number"):
				report(marker.line, f"{marker.text}: {name.text} takes a number")
				return specs
			value = unquote(token) if kind == "string" else float(token.text) * (-1 if negate else 1)
			i += 1
		elif kind != "flag":
			report(marker.line, f"{marker.text}: {name.text} needs a value, as {name.text} = ...")
			return specs
		specs[name.text] = value
		if i < len(tokens):
			if tokens[i].text != ",":
				report(marker.line, f"{marker.text}: expected ',' between specifiers, found '{tokens[i].text}'")
				return specs
			i += 1
	return specs


class HeaderParser:
	"""Finds components, BLK_PROPERTY members, enums and data members in one header.

	Not a C++ parser: it tracks class/namespace/function scopes and splits class
	bodies into statements, which is enough for member declarations. Anything it
	gets wrong about a property's type is caught by the static_assert AddField
	emits.
	"""

	def __init__(self, path, text, diag):
		self.path = path
		self.toks = tokenize(text)
		self.diag = diag
		self.components = []
		self.enums = []
		self.members = []

	def text(self, i):
		return self.toks[i].text if i < len(self.toks) else ""

	def error(self, line, msg):
		self.diag.error(self.path, line, msg)

	def match(self, i):
		"""Index of the bracket that closes the one at i."""
		open_ = self.toks[i].text
		close = {"(": ")", "{": "}", "[": "]"}[open_]
		depth = 0
		for j in range(i, len(self.toks)):
			t = self.toks[j]
			if t.kind != "punct":
				continue
			if t.text == open_:
				depth += 1
			elif t.text == close:
				depth -= 1
				if depth == 0:
					return j
		return len(self.toks) - 1

	def parse(self):
		toks = self.toks
		stack = [Frame("file")]
		i = 0
		while i < len(toks):
			t = toks[i]
			top = stack[-1]
			if t.kind == "pp":
				i += 1
				continue
			if top.kind == "block":
				if t.kind == "punct" and t.text == "{":
					stack.append(Frame("block"))
				elif t.kind == "punct" and t.text == "}":
					stack.pop()
					if top.closes_stmt:
						self.reset(stack[-1])
				i += 1
				continue

			if t.kind == "ident":
				nxt = self.text(i + 1)
				if t.text == "BLK_DECLARE_COMPONENT" and nxt == "(":
					i = self.declare_component(i, top)
					continue
				if t.text in ("public", "protected", "private") and nxt == ":":
					self.reset(top)
					i += 2
					continue
				if t.text == "BLK_PROPERTY" and not top.stmt:
					i = self.property_marker(i, top)
					continue
				if t.text == "BLK_ENUM":
					self.error(t.line, "BLK_ENUM marks an enumerator; it can't be used here")
				if t.text == "namespace" and not top.stmt:
					j = i + 1
					while toks[j].kind == "ident" or toks[j].text == "::":
						j += 1
					if toks[j].text == "{":
						name = "".join(x.text for x in toks[i + 1:j])
						stack.append(Frame("namespace", qualname=scoped(top.qualname, name)))
						i = j + 1
						continue
				if t.text in ("class", "struct", "union"):
					head = self.class_head(i)
					if head:
						brace, name = head
						if top.marker:
							self.error(top.marker[1].line, "BLK_PROPERTY must be followed by a data member declaration")
							top.marker = None
						qualname = scoped(top.qualname, name or "<anonymous>")
						stack.append(Frame("class", qualname=qualname, name=name))
						i = brace + 1
						continue
				if t.text == "enum":
					end = self.enum_definition(i, top)
					if end is not None:
						i = end
						continue
			elif t.kind == "punct":
				if t.text == "{":
					if self.is_function_body(top.stmt):
						if top.marker:
							self.error(top.marker[1].line, "BLK_PROPERTY must be followed by a data member declaration")
							top.marker = None
						stack.append(Frame("block", closes_stmt=True))
						i += 1
						continue
					# A brace initializer: part of the statement.
					j = self.match(i)
					top.stmt.extend(toks[i:j + 1])
					i = j + 1
					continue
				if t.text == "}":
					if top.kind in ("class", "namespace"):
						stack.pop()
						if top.kind == "class":
							self.close_class(top)
							# The class definition was the statement; what follows is at most declarators.
							stack[-1].skip_stmt = True
					i += 1
					continue
				if t.text == ";":
					self.end_statement(top)
					i += 1
					continue
			top.stmt.append(t)
			i += 1
		return self

	@staticmethod
	def reset(frame):
		frame.stmt = []
		frame.skip_stmt = False
		frame.marker = None

	@staticmethod
	def is_function_body(stmt):
		texts = [t.text for t in stmt]
		if "(" not in texts:
			return not texts  # a bare block; otherwise a brace initializer
		# Constructor member-initializer list: Foo() : m_a{1}, m_b{2} {
		if ")" in texts and ":" in texts[texts.index(")"):] and (stmt[-1].kind == "ident" or texts[-1] == ">"):
			return False
		return True

	def class_head(self, i):
		"""(index of '{', name) if the class/struct keyword at i starts a definition."""
		toks = self.toks
		j = i + 1
		name = None
		if j < len(toks) and toks[j].kind == "ident" and toks[j].text not in ("abstract", "final", "sealed"):
			name = toks[j].text
			j += 1
		while self.text(j) in ("abstract", "final", "sealed"):
			j += 1
		if self.text(j) == ":":
			while j < len(toks) and toks[j].text not in ("{", ";", "(", ")", "="):
				j += 1
		if self.text(j) == "{":
			return j, name
		return None

	def declare_component(self, i, top):
		t = self.toks[i]
		close = self.match(i + 1)
		args = self.toks[i + 2:close]
		name = args[0].text if args else ""
		parent = "".join(x.text for x in args[2:]) if len(args) > 2 else ""
		if top.kind != "class" or top.name != name:
			self.error(t.line, f"BLK_DECLARE_COMPONENT({name}) must be inside class {name}")
		else:
			top.component = Component(name, parent, top.qualname, self.path, t.line)
			self.components.append(top.component)
		self.reset(top)
		j = close + 1
		if self.text(j) == ";":
			j += 1
		return j

	def property_marker(self, i, top):
		t = self.toks[i]
		j = i + 1
		if self.text(j) != "(":
			self.error(t.line, "BLK_PROPERTY needs parentheses, even with no specifiers: BLK_PROPERTY()")
			specs = {}
		else:
			close = self.match(j)
			specs = parse_specifiers(self.toks[j + 1:close], PROPERTY_SPECIFIERS, t, self.error)
			j = close + 1
		if top.kind != "class":
			self.error(t.line, "BLK_PROPERTY must be inside a class")
		else:
			top.marker = (specs, t)
		return j

	def enum_definition(self, i, top):
		"""Records an enum definition starting at i; returns the index past it, or None."""
		toks = self.toks
		j = i + 1
		if self.text(j) in ("class", "struct"):
			j += 1
		name = None
		if j < len(toks) and toks[j].kind == "ident":
			name = toks[j].text
			j += 1
		if self.text(j) == ":":
			while j < len(toks) and toks[j].text not in ("{", ";"):
				j += 1
		if self.text(j) != "{":
			return None  # a forward declaration or an elaborated type specifier
		close = self.match(j)
		if name:
			enumerators, problem = self.enumerators(j + 1, close)
			self.enums.append(Enum(name, scoped(top.qualname, name), self.path, toks[i].line, enumerators, problem))
		if top.marker:
			self.error(top.marker[1].line, "BLK_PROPERTY must be followed by a data member declaration")
		top.marker = None
		top.skip_stmt = True
		return close + 1

	def enumerators(self, start, end):
		chunks, cur, depth = [], [], 0
		problem = None
		for t in self.toks[start:end]:
			if t.kind == "pp":
				problem = "preprocessor directives inside a reflected enum aren't supported"
				continue
			if t.kind == "punct" and t.text in ("(", "[", "{"):
				depth += 1
			elif t.kind == "punct" and t.text in (")", "]", "}"):
				depth -= 1
			if t.kind == "punct" and t.text == "," and depth == 0:
				chunks.append(cur)
				cur = []
			else:
				cur.append(t)
		chunks.append(cur)

		result = []
		for chunk in chunks:
			if not chunk:
				continue
			ident = chunk[0]
			if ident.kind != "ident":
				problem = problem or f"can't read enumerator at '{ident.text}'"
				continue
			saved_name, skip = None, False
			k = 1
			while k < len(chunk):
				x = chunk[k]
				if x.text == "BLK_ENUM":
					if k + 1 >= len(chunk) or chunk[k + 1].text != "(":
						problem = problem or "BLK_ENUM needs parentheses: BLK_ENUM(Skip)"
						break
					close, depth = None, 0
					for idx in range(k + 1, len(chunk)):
						if chunk[idx].kind != "punct":
							continue
						depth += (chunk[idx].text == "(") - (chunk[idx].text == ")")
						if depth == 0:
							close = idx
							break
					if close is None:
						problem = problem or f"unclosed BLK_ENUM( after {ident.text}"
						break
					messages = []
					specs = parse_specifiers(chunk[k + 2:close], ENUM_SPECIFIERS, x, lambda line, msg: messages.append(msg))
					if messages:
						problem = problem or messages[0]
						break
					saved_name = specs.get("SerializedAs", saved_name)
					skip = skip or bool(specs.get("Skip"))
					k = close + 1
					continue
				if x.text == "=":
					problem = problem or f"{ident.text} has an explicit value, but saved enums are matched by position"
				else:
					problem = problem or f"unexpected '{x.text}' after enumerator {ident.text}"
				break
			result.append(Enumerator(ident.text, saved_name, skip, ident.line, ident.pos + len(ident.text)))
		return result, problem

	def close_class(self, frame):
		if frame.marker:
			self.error(frame.marker[1].line, "BLK_PROPERTY must be followed by a data member declaration")
		if not frame.props:
			return
		if frame.component is None:
			for p in frame.props:
				self.error(p.line, f"BLK_PROPERTY in {frame.name}, which has no BLK_DECLARE_COMPONENT")
		else:
			frame.component.props.extend(frame.props)

	def end_statement(self, top):
		if top.skip_stmt:
			self.reset(top)
			return
		stmt, marker = top.stmt, top.marker
		if top.kind == "class" and stmt:
			decl, problem = analyze_member(stmt)
			if decl:
				name, type_tokens = decl
				self.members.append(Member(top.qualname, name, type_tokens, problem, self.path, stmt[0].line, stmt[0].pos))
			if marker:
				if decl is None or problem:
					self.error(marker[1].line, problem or "BLK_PROPERTY must be followed by a data member declaration")
				else:
					top.props.append(Property(decl[0], decl[1], marker[0].get("SerializedAs"), marker[1].line, marker[0]))
		elif marker:
			self.error(marker[1].line, "BLK_PROPERTY must be followed by a data member declaration")
		self.reset(top)


NOT_DATA = {"typedef", "using", "friend", "virtual", "explicit", "template", "static_assert", "operator"}


def analyze_member(stmt):
	"""((name, type tokens), problem) for a data member declaration, else (None, None)."""
	k = 0
	static = False
	while k < len(stmt) and stmt[k].text in ("static", "mutable", "inline", "constexpr", "thread_local"):
		static |= stmt[k].text == "static"
		k += 1
	if k >= len(stmt) or stmt[k].text in NOT_DATA or any(t.text == "operator" for t in stmt):
		return None, None

	problem = "static members can't be reflected" if static else None
	angle = paren = 0
	end = len(stmt)
	for idx in range(k, len(stmt)):
		t = stmt[idx]
		if t.kind != "punct":
			continue
		x = t.text
		if x == "<":
			angle += 1
		elif x == ">" and angle:
			angle -= 1
		elif x in ("(", "["):
			if angle == 0 and paren == 0:
				if x == "(":
					return None, None  # a function
				problem = problem or "C arrays can't be reflected; use std::vector"
				end = idx
				break
			paren += 1
		elif x in (")", "]"):
			paren -= 1
		elif angle == 0 and paren == 0:
			if x in ("=", "{"):
				end = idx
				break
			if x == ",":
				problem = problem or "declare one member per BLK_PROPERTY"
			elif x == ":":
				problem = problem or "bit-fields can't be reflected"
				end = idx
				break

	decl = stmt[k:end]
	if len(decl) < 2 or decl[-1].kind != "ident":
		return None, None
	return (decl[-1].text, decl[:-1]), problem


