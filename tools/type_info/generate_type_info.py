# Tokenizer

TOKEN_RE = re.compile(
	r"""
	(?P<nl>\n)
	|(?P<ws>[ \t\r\f\v]+)
	|(?P<comment>//[^\n]*|/\*.*?\*/)
	|(?P<string>"(?:\\.|[^"\\\n])*")
	|(?P<char>'(?:\\.|[^'\\\n])*')
	|(?P<ident>[A-Za-z_]\w*)
	|(?P<number>\.?\d(?:[eEpP][+-]|[\w.'])*)
	|(?P<punct>::|->|[^\s\w])
	|(?P<other>.)
	""",
	re.S | re.X,
)


@dataclass(slots=True)
class Token:
	kind: str  # ident, number, string, char, punct, other, pp
	text: str
	pos: int
	line: int


def tokenize(text):
	tokens = []
	pos, line, line_start = 0, 1, True
	n = len(text)
	while pos < n:
		m = TOKEN_RE.match(text, pos)
		kind, s = m.lastgroup, m.group()
		if kind == "nl":
			line += 1
			line_start = True
		elif kind == "ws":
			pass
		elif kind == "comment":
			line += s.count("\n")
		elif s == "#" and line_start:
			# A preprocessor directive, backslash continuations included.
			start_line, end = line, pos
			while True:
				nl = text.find("\n", end)
				if nl == -1:
					end = n
					break
				if text[end:nl].rstrip("\r").endswith("\\"):
					end = nl + 1
					line += 1
					continue
				end = nl
				break
			tokens.append(Token("pp", text[pos:end], pos, start_line))
			pos = end
			continue
		else:
			line_start = False
			tokens.append(Token(kind, s, pos, line))
		pos = m.end()
	return drop_disabled(tokens)


def drop_disabled(tokens):
	"""Removes code inside #if 0 blocks."""
	out, skip = [], 0
	for t in tokens:
		directive = t.text[1:].split() if t.kind == "pp" else []
		word = directive[0] if directive else ""
		if skip:
			if word in ("if", "ifdef", "ifndef"):
				skip += 1
			elif word == "endif" or (word in ("else", "elif") and skip == 1):
				skip -= 1
			continue
		if word == "if" and directive[1:2] == ["0"]:
			skip = 1
			continue
		out.append(t)
	return out


