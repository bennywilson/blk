@dataclass
class Field:
	saved_name: str
	tag: str
	member: str
	is_array: bool
	struct_name: str
	cpp_type: str
	line: int
	min_val: float | None = None
	max_val: float | None = None


def type_text(tokens):
	out, prev_word = "", False
	for t in tokens:
		word = t.kind in ("ident", "number")
		if out and word and prev_word:
			out += " "
		out += t.text
		prev_word = word
	return out


def qualify_std(text):
	return re.sub(r"(?<![\w:])vector<", "std::vector<", text)


def normalize(tokens):
	kept = [t for t in tokens if t.text not in ("const", "volatile", "class", "struct", "enum", "typename")]
	text = qualify_std(type_text(kept))
	return "std::string" if text == "string" else text


def derive_name(member):
	"""m_min_spawn_rate -> MinSpawnRate, m_pWaveFile -> WaveFile, m_start_3d_offset -> Start3DOffset."""
	s = member[2:] if member.startswith("m_") else member
	if len(s) > 1 and s[0] in "pb" and s[1].isupper():
		s = s[1:]
	name = "".join(part[:1].upper() + part[1:] for part in s.split("_") if part)
	return re.sub(r"(?<=\d)[a-z]", lambda m: m.group().upper(), name)


def shared_prefix(idents):
	"""The prefix every enumerator shares, up to its last underscore: CullMode_ for CullMode_None."""
	if not idents:
		return ""
	common = os.path.commonprefix(idents)
	return common[:common.rfind("_") + 1]


def parse_tree(roots, diag, exclude):
	parsers = []
	for root in roots:
		for dirpath, dirnames, filenames in os.walk(os.path.join(REPO, root)):
			dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
			for f in sorted(filenames):
				if not f.endswith(".h"):
					continue
				path = os.path.normpath(os.path.join(dirpath, f))
				if path in exclude:
					continue
				with open(path, encoding="utf-8", errors="surrogateescape", newline="") as fh:
					text = fh.read()
				if "enum" not in text and "BLK_" not in text:
					continue
				parsers.append(HeaderParser(path, text, diag).parse())
	return parsers


class Resolver:
	def __init__(self, parsers):
		self.components = {}
		self.enums = {}
		for p in parsers:
			for c in p.components:
				self.components.setdefault(c.name, c)
			for e in p.enums:
				self.enums.setdefault(e.qualname, e)

	def find_enum(self, name, comp):
		if "::" in name:
			return self.enums.get(name)
		c = comp
		while c is not None:
			e = self.enums.get(f"{c.qualname}::{name}")
			if e:
				return e
			c = self.components.get(c.parent)
		return self.enums.get(name)

	def field(self, prop, comp, diag, used_enums):
		norm = normalize(prop.type_tokens)
		m = re.fullmatch(r"std::vector<(.+)>", norm)
		elem = m.group(1) if m else norm
		is_array = m is not None
		cpp_type = qualify_std(type_text(prop.type_tokens))

		enum = None if elem in SCALAR_TAGS else self.find_enum(elem, comp)
		if elem in SCALAR_TAGS:
			tag, struct_name = SCALAR_TAGS[elem], ""
			if is_array:
				struct_name = PRIMITIVE_ARRAY_KEYS.get(elem)
				if struct_name is None:
					diag.error(comp.path, prop.line, f"std::vector<{elem}> has no vector operations registered in NameToTypeInfoMap()")
					return None
		elif enum is not None:
			if is_array:
				diag.error(comp.path, prop.line, "arrays of enums can't be reflected")
				return None
			tag, struct_name = "ENUM", enum.name
			used_enums.setdefault(enum.qualname, enum)
			if "::" not in elem and enum.qualname != enum.name:
				cpp_type = re.sub(rf"(?<![\w:]){re.escape(elem)}\b", enum.qualname, cpp_type)
		elif elem in self.components:
			tag, struct_name = "STRUCT", elem
		else:
			diag.error(comp.path, prop.line, f"no BLK_TYPEINFO tag for type '{norm}'; add it to SCALAR_TAGS in {os.path.relpath(__file__, REPO)}")
			return None

		min_val, max_val = prop.specs.get("MinVal"), prop.specs.get("MaxVal")
		if min_val is not None or max_val is not None:
			if is_array or tag not in ("FLOAT", "INT"):
				diag.error(comp.path, prop.line, f"MinVal/MaxVal only apply to a single FLOAT or INT property, and {prop.member} is '{norm}'")
				min_val = max_val = None
			elif min_val is not None and max_val is not None and min_val > max_val:
				diag.error(comp.path, prop.line, f"MinVal {min_val:g} is greater than MaxVal {max_val:g}")
				min_val = max_val = None

		derived = derive_name(prop.member)
		if prop.saved_name == derived:
			diag.warning(comp.path, prop.line, f'BLK_PROPERTY derives "{derived}" from {prop.member} already; use plain BLK_PROPERTY')
		saved_name = prop.saved_name or derived
		return Field(saved_name, tag, prop.member, is_array, struct_name, cpp_type, prop.line, min_val, max_val)


def enum_values(enum, diag):
	if enum.problem:
		diag.error(enum.path, enum.line, f"enum {enum.name}: {enum.problem}")
	first_skip = next((k for k, x in enumerate(enum.enumerators) if x.skip), len(enum.enumerators))
	if any(not x.skip for x in enum.enumerators[first_skip:]):
		diag.error(enum.path, enum.line, f"enum {enum.name}: BLK_ENUM_SKIP only works on trailing enumerators - saved enums are matched by position")
	kept = enum.enumerators[:first_skip]
	prefix = shared_prefix([x.ident for x in kept])
	values = []
	for x in kept:
		derived = x.ident[len(prefix):]
		if x.saved_name == derived:
			diag.warning(enum.path, x.line, f'{x.ident} is saved as "{derived}" already; drop the SerializedAs')
		values.append((x.ident, x.saved_name if x.saved_name is not None else derived))
	return values


def generate(project, diag):
	cfg = PROJECTS[project]
	outputs = {os.path.normpath(os.path.join(REPO, p[k])) for p in PROJECTS.values() for k in ("tables", "instances")}
	scan = parse_tree(cfg["scan"], diag, outputs)
	context = parse_tree(cfg["context"], Diagnostics(), outputs)  # the context project reports its own problems
	resolver = Resolver(scan + context)

	components = [c for p in scan for c in p.components]
	seen_components = {}
	for c in components:
		if c.name in seen_components:
			diag.error(c.path, c.line, f"{c.name} is declared twice (also {seen_components[c.name]})")
		seen_components[c.name] = f"{c.path}({c.line})"

	# Enums the context project already reflects.
	context_enums = {}
	for p in context:
		for c in p.components:
			for prop in c.props:
				resolver.field(prop, c, Diagnostics(), context_enums)

	used_enums, classes = {}, []
	for c in components:
		if not c.props:
			diag.error(c.path, c.line, f"{c.name} has no BLK_PROPERTY members; TypeInfoHierarchyIterator needs at least one per class")
		fields, saved = [], {}
		for prop in c.props:
			f = resolver.field(prop, c, diag, used_enums)
			if f is None:
				continue
			if f.saved_name in saved:
				diag.error(c.path, prop.line, f'{c.name} already saves a property as "{f.saved_name}" (line {saved[f.saved_name]})')
			saved[f.saved_name] = prop.line
			fields.append(f)
		classes.append((c, fields))

	# A key has to be unique across the whole hierarchy, not just one class: the loader
	# takes the first match walking the ancestor chain, so a derived class repeating an
	# inherited key silently reads into the ancestor's member.
	keys_by_class = {c.name: {f.saved_name: f for f in fields} for c, fields in classes}
	for c, fields in classes:
		ancestor = resolver.components.get(c.parent)
		while ancestor is not None:
			for name, f in keys_by_class.get(ancestor.name, {}).items():
				mine = keys_by_class[c.name].get(name)
				if mine is not None:
					diag.error(c.path, mine.line, f'{c.name}::{mine.member} is saved as "{name}", which {ancestor.name}::{f.member} already uses; the loader would read into {ancestor.name}\'s member')
			ancestor = resolver.components.get(ancestor.parent)

	scan_enums = {id(e) for p in scan for e in p.enums}
	enums, enum_names = [], {}
	for qualname, e in used_enums.items():
		if id(e) not in scan_enums:
			if qualname not in context_enums:
				diag.error(e.path, e.line, f"enum {e.name} is used by a {project} property but defined in, and not reflected by, another project")
			continue
		if e.name in enum_names:
			diag.error(e.path, e.line, f"two reflected enums are named {e.name} (also {enum_names[e.name]})")
		enum_names[e.name] = f"{e.path}({e.line})"
		enums.append(e)
	enums.sort(key=lambda e: (e.path, e.line))
	enum_blocks = [(e, enum_values(e, diag)) for e in enums]

	return emit_tables(enum_blocks, classes), emit_instances(enum_blocks, classes)


def emit_tables(enum_blocks, classes):
	out = [HEADER, "// clang-format off"]
	for e, values in enum_blocks:
		out.append("GenerateEnum(")
		out.append(f'\t{e.name}, "{e.name}",')
		out += [f'\tAddEnumField({ident}, "{name}")' for ident, name in values]
		out += [")", ""]
	for c, fields in classes:
		out.append("GenerateClass(")
		out.append(f"\t{c.name},")
		for f in fields:
			is_array = "true" if f.is_array else "false"
			out.append(f'\tAddField("{f.saved_name}", BLK_TYPEINFO_{f.tag}, {c.name}, {f.member}, {is_array}, "{f.struct_name}", {f.cpp_type})')
			if f.min_val is not None:
				out.append(f'\tSetFieldMin("{f.saved_name}", {f.min_val:g})')
			if f.max_val is not None:
				out.append(f'\tSetFieldMax("{f.saved_name}", {f.max_val:g})')
		out += [")", ""]
	return "\n".join(out)


def emit_instances(enum_blocks, classes):
	out = [HEADER, "// clang-format off"]
	out += [f"{e.name}_Enum {e.name}_EnumClass;" for e, _ in enum_blocks]
	out += [f"BLK_DEFINE_CLASS({c.name})" for c, _ in classes]
	return "\n".join(out) + "\n"


def main():
	ap = argparse.ArgumentParser(description="Generate reflection tables from BLK_PROPERTY markers.")
	ap.add_argument("projects", nargs="*", metavar="project", help=f"{' or '.join(PROJECTS)} (default: all)")
	ap.add_argument("--check", action="store_true", help="exit 1 if an output is stale instead of writing it")
	args = ap.parse_args()
	for p in args.projects:
		if p not in PROJECTS:
			ap.error(f"unknown project {p!r}")

	diag = Diagnostics()
	writes = []
	for p in args.projects or list(PROJECTS):
		tables, instances = generate(p, diag)
		writes += [(PROJECTS[p]["tables"], tables), (PROJECTS[p]["instances"], instances)]

	for w in diag.warnings:
		print(w)
	if diag.errors:
		for e in diag.errors:
			print(e)
		return 1

	stale = False
	for rel, content in writes:
		path = os.path.join(REPO, rel)
		new = content.replace("\n", "\r\n")
		try:
			with open(path, encoding="utf-8", newline="") as fh:
				old = fh.read()
		except FileNotFoundError:
			old = None
		if old == new:
			continue
		if args.check:
			print(f"{os.path.normpath(path)}(1): error TYPEINFO: out of date; run python {os.path.relpath(__file__, REPO)}")
			stale = True
			continue
		with open(path, "w", encoding="utf-8", newline="") as fh:
			fh.write(new)
		print(f"type_info: regenerated {rel}")
	return 1 if stale else 0


if __name__ == "__main__":
	sys.exit(main())
